/**
 * Flag emoji for an ISO 3166-1 alpha-2 code, built from Unicode regional
 * indicator symbols (U+1F1E6..U+1F1FF). No assets, no dependency.
 * Returns an empty string for anything that isn't two ASCII letters.
 */
export function flagEmoji(countryCode: string): string {
  const code = (countryCode ?? '').trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return '';
  return String.fromCodePoint(
    ...[...code].map((ch) => 0x1f1e6 + (ch.charCodeAt(0) - 65)),
  );
}

/** Hard cap so a huge country's city list can't blow up the dropdown. */
export const CITY_LIMIT = 300;

/**
 * Major cities for a country, sorted alphabetically and capped at CITY_LIMIT.
 *
 * `country-state-city` ships a multi-MB city dataset, so it is imported
 * lazily here — the data only loads when the user actually opens the city
 * dropdown, never in the initial bundle. Callers should offer an
 * "Other (type your city)" fallback since this list isn't exhaustive.
 */
export async function citiesForCountry(countryCode: string): Promise<string[]> {
  const code = (countryCode ?? '').trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return [];
  const { City } = await import('country-state-city');
  const names = Array.from(
    new Set((City.getCitiesOfCountry(code) ?? []).map((c) => c.name)),
  ).sort((a, b) => a.localeCompare(b));
  return names.slice(0, CITY_LIMIT);
}
